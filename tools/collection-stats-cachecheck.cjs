const assert = require('node:assert/strict'), { buildSync } = require('esbuild'), path = require('node:path');
const bundle = buildSync({ entryPoints: [path.resolve('src/core/collectionStatsCache.ts')], bundle: true, platform: 'node', format: 'cjs', write: false });
const moduleObject = { exports: {} }; new Function('module', 'exports', bundle.outputFiles[0].text)(moduleObject, moduleObject.exports);
const { CollectionStatsCache } = moduleObject.exports;
(async () => {
  let disk = '', writes = 0, time = 1000000;
  const storage = { exists: async () => !!disk, read: async () => disk, write: async (_, value) => { disk = value; writes++; } };
  const create = () => new CollectionStatsCache(storage, 'cache.json', () => time);
  let cache = create();
  await cache.put('42', 'album:1', 10, { count: 10, duration: 3600000 });
  await cache.put('42', 'playlist:2', 5, { count: 5, duration: 600000 });
  await cache.flush(); assert.equal(writes, 1);
  cache = create();
  assert.deepEqual(await cache.get('42', 'album:1', 10), { stats: { count: 10, duration: 3600000 }, fresh: true });
  assert.equal(await cache.get('43', 'album:1', 10), null);
  assert.equal((await cache.get('42', 'album:1', 11)).fresh, false);
  time += 6 * 3600000;
  assert.equal((await cache.get('42', 'playlist:2', 5)).fresh, false);
  assert.equal((await cache.get('42', 'album:1', 10)).fresh, true);
  time += 30 * 86400000;
  assert.equal((await cache.get('42', 'album:1', 10)).fresh, false);
  assert.equal((await cache.get('42', 'album:1', 10)).stats.duration, 3600000);
  await cache.put('42', 'playlist:3', 1, { count: 1 });
  time += 5 * 60000; assert.equal((await cache.get('42', 'playlist:3', 1)).fresh, false);
  await cache.put('secret-cookie', 'album:1', 1, { count: 1, duration: 1 }); await cache.flush();
  assert.ok(!disk.includes('secret-cookie'));
  for (let id = 10; id < 2020; id++) await cache.put('42', 'album:' + id, 1, { count: 1, duration: 100 });
  await cache.flush(); assert.equal(JSON.parse(disk).entries.length, 2000);
  assert.equal(await cache.get('42', 'album:1', 10), null);
  disk = '{invalid'; cache = create(); assert.equal(await cache.get('42', 'album:1', 10), null);
  await cache.put('public', 'album:1', 0, { count: 0, duration: 0 }); await cache.flush();
  assert.equal((await create().get('public', 'album:1', 0)).fresh, true);
  const broken = new CollectionStatsCache({ exists: async () => { throw Error(); }, read: async () => '', write: async () => { throw Error(); } }, 'cache');
  await broken.put('1', 'album:1', 1, { count: 1, duration: 100 }); await broken.flush();
  assert.equal((await broken.get('1', 'album:1', 1)).stats.duration, 100);
  console.log('Persistent statistics: restart, account isolation, expiry, count changes, incomplete data, limits, corruption and I/O fallback passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
