const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const notices = [];
function load(entry) {
  const result = buildSync({ entryPoints: [entry], bundle: true, platform: 'node', format: 'cjs', external: ['obsidian'], write: false });
  const module = { exports: {} };
  const host = new Proxy({}, { get: (_, key) => key === 'Notice' ? class { constructor(text) { notices.push(text); } } : key === 'Platform' ? {} : class {} });
  new Function('module', 'exports', 'require', result.outputFiles[0].text)(module, module.exports, name => name === 'obsidian' ? host : require(name));
  return module.exports;
}
const { wallCollectionId, collectionUrl } = load('src/core/collection.ts');
const { emptyWall, insertItem, parseWall, serializeWall, mergeWalls } = load('src/core/store.ts');
const { normalizeOrder, moveWithin, removeFromOrder } = load('src/core/layout.ts');
const { MusicLibraryApi } = load('src/core/library.ts');
const { playAlbum, h5FallbackUrl } = load('src/core/playback.ts');
const { MusicLibraryView } = load('src/ui/MusicLibraryView.ts');
const album = { albumId: 42, name: 'Album', artist: 'Artist', cover: '', trackCount: 1, tracks: [{ id: 1, name: 'Old', duration: 100 }] };
const playlist = { ...album, albumId: 0, playlistId: 42, name: 'Playlist' };
const item = meta => ({ albumId: wallCollectionId(meta), meta, source: 'search', locked: true, addedAt: new Date().toISOString() });
(async () => {
  const wall = emptyWall('Mixed', 'vinyl'); wall.order = [];
  assert.equal(insertItem(wall, item(album)), true);
  assert.equal(insertItem(wall, item(playlist)), true);
  assert.equal(insertItem(wall, item(playlist)), false);
  const restored = parseWall(serializeWall(wall));
  assert.deepEqual(restored.items.map(i => i.albumId), [42, -42]);
  assert.deepEqual(normalizeOrder(restored.items, restored.order), [42, -42]);
  assert.deepEqual(moveWithin(restored.order, -42, 42, 'before'), [-42, 42]);
  assert.deepEqual(removeFromOrder(restored.order, [-42]), [42]);
  const target = emptyWall('Target', 'cd');
  assert.deepEqual(mergeWalls(target, restored), { addedCount: 2, skippedCount: 0 });
  assert.deepEqual(mergeWalls(target, restored), { addedCount: 0, skippedCount: 2 });
  assert.equal(parseWall(JSON.stringify({ version: 2, items: [item(album)] })).items.length, 1);
  assert.equal(parseWall(JSON.stringify({ version: 3, items: [{ ...item(playlist), albumId: 42 }] })).items.length, 0);
  assert.match(collectionUrl(playlist), /playlist\?id=42$/);
  assert.match(h5FallbackUrl(album), /album\?id=42$/);
  const api = new MusicLibraryApi(() => {}); let revision = 0, calls = 0;
  api.call = async () => { calls++; return { playlist: { id: 42, name: `Live ${++revision}`, creator: { nickname: 'Live owner' }, description: 'Live description', tags: ['Jazz'], trackIds: [{ id: 2 }, { id: 1 }], trackCount: 2 } }; };
  api.songs = async ids => ids.map(id => ({ id, name: `Song ${id}`, duration: 100 }));
  const summary = { id: 42, name: 'Stale', creator: 'Old owner', count: 1, cover: '' };
  const first = await api.detail(summary, ''), second = await api.detail(summary, '');
  assert.equal(calls, 2); assert.equal(first.name, 'Live 1'); assert.equal(second.name, 'Live 2');
  assert.equal(second.artist, 'Live owner'); assert.equal(second.description, 'Live description');
  assert.deepEqual(second.tracks.map(t => t.id), [2, 1]);
  api.call = async () => ({});
  await assert.rejects(api.detail(summary, ''));
  let played, live = true;
  const deps = { isDesktop: false, request() {}, loadCollection: async () => second, playInside: async meta => { played = meta; return true; }, isCurrent: () => live };
  await playAlbum(playlist, deps); assert.equal(played.name, 'Live 2');
  played = undefined;
  await playAlbum(playlist, { ...deps, loadCollection: async () => { throw new Error('Offline'); } });
  assert.equal(played, undefined); assert.equal(notices.length, 1);
  await playAlbum(playlist, { ...deps, loadCollection: async () => { live = false; return second; } });
  assert.equal(played, undefined);
  const view = Object.create(MusicLibraryView.prototype); let opened;
  view.openPlaylist = async value => { opened = value; };
  view.openAlbum = async value => { opened = value; };
  await view.showCollection(playlist); assert.equal(opened.id, 42);
  await view.showCollection(album); assert.equal(opened.albumId, 42);
  console.log('Playlist wall checks passed: collision-free keys, persistence, legacy files, sorting, migration, links, live details, failed/stale request guards and detail routing.');
})().catch(error => { console.error(error); process.exitCode = 1; });
